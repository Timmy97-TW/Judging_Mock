#!/usr/bin/env python3
"""Merge data/sections/*.json into data/questions.js.

Order is the ORDER list below, not the filesystem. Run from anywhere:
    python3 tools/build.py
"""

import json
import os
import sys

ORDER = [
    "plant-stress",
    "protectant-design",
    "gene-circuit",
    "bioreactor-hardware",
    "human-practices",
    "business",
    "biomanufacturing",
    "general-team",
]

TYPES = {"fact", "decision", "boundary", "alternative", "weakness"}
FIELDS = ("id", "type", "q", "q_zh", "answer", "answer_zh", "cite", "trap", "trap_zh")

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "data", "sections")

sections = []
problems = []
seen = set()

for slug in ORDER:
    path = os.path.join(src, slug + ".json")
    if not os.path.exists(path):
        problems.append("missing section file: " + slug + ".json")
        continue
    with open(path, encoding="utf-8") as fh:
        sec = json.load(fh)
    out = {k: sec.get(k, "") for k in ("slug", "title", "title_zh", "blurb", "blurb_zh")}
    out["slug"] = slug
    qs = []
    for q in sec.get("questions", []):
        if q["type"] not in TYPES:
            problems.append("%s: unknown type %r" % (q.get("id"), q["type"]))
        if q["id"] in seen:
            problems.append("duplicate id " + q["id"])
        seen.add(q["id"])
        for k in ("q", "q_zh", "answer", "answer_zh"):
            if not q.get(k):
                problems.append("%s: empty %s" % (q.get("id"), k))
        item = {k: q[k] for k in FIELDS if q.get(k)}
        item.setdefault("cite", [])
        qs.append(item)
    out["questions"] = qs
    sections.append(out)

counts = {t: 0 for t in TYPES}
for s in sections:
    for q in s["questions"]:
        counts[q["type"]] = counts.get(q["type"], 0) + 1

data = {"wiki": "https://timmy97-tw.github.io/releaf-wiki/", "sections": sections}
dest = os.path.join(root, "data", "questions.js")
with open(dest, "w", encoding="utf-8") as fh:
    fh.write("/* Generated by tools/build.py from data/sections/*.json. Do not edit by hand. */\n")
    fh.write("window.QB = ")
    json.dump(data, fh, ensure_ascii=False, indent=1)
    fh.write(";\n")

total = sum(len(s["questions"]) for s in sections)
for s in sections:
    print("%-22s %3d" % (s["slug"], len(s["questions"])))
print("-" * 26)
print("%-22s %3d" % ("total", total))
print("by type: " + ", ".join("%s %d" % (k, counts[k]) for k in sorted(counts)))
if problems:
    print("\nproblems:")
    for p in problems:
        print("  " + p)
    sys.exit(1)
